function escapePdfText(input: string): string {
  return input
    .replace(/[^\x20-\x7E]/g, ' ')
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');
}

function wrapLine(text: string, maxLen = 84): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let current = '';
  for (const w of words) {
    if ((current + ' ' + w).trim().length > maxLen) {
      if (current) lines.push(current);
      current = w;
    } else {
      current = (current + ' ' + w).trim();
    }
  }
  if (current) lines.push(current);
  return lines.length ? lines : [''];
}

export function buildNotificationPdf(notif: Record<string, unknown>): Buffer {
  const lines: { text: string; bold?: boolean; size?: number }[] = [
    { text: 'GOVTRACK - OFFICIAL RECRUITMENT NOTIFICATION SUMMARY', bold: true, size: 13 },
    { text: '==========================================================================', size: 9 },
    { text: '' },
    { text: String(notif.title || 'Untitled Notification'), bold: true, size: 12 },
    { text: '' },
  ];

  const fields: [string, unknown][] = [
    ['Organization', notif.organization_name],
    ['Notification No.', notif.notification_number],
    ['Job Category', notif.job_category],
    ['Qualification', notif.qualification],
    ['State / Region', notif.state],
    ['Vacancy Count', notif.vacancy_count],
    ['Published Date', notif.published_date],
    ['Application Start', notif.application_start_date],
    ['Application Deadline', notif.application_deadline],
    ['Examination Date', notif.exam_date],
    ['Admit Card Date', notif.admit_card_date],
    ['Result Date', notif.result_date],
    ['Source Mode', notif.is_demo_data ? 'DEMO DATA (Offline HTML Fixture)' : 'Live Extracted'],
    ['Original Source URL', notif.source_url],
    ['Official PDF URL', notif.pdf_url],
    ['First Seen At', notif.first_seen_at],
    ['Last Checked At', notif.last_seen_at],
  ];

  for (const [label, val] of fields) {
    const valStr = val ? String(val) : 'Not available';
    const wrapped = wrapLine(`${label}: ${valStr}`, 84);
    for (const w of wrapped) {
      lines.push({ text: w, size: 10 });
    }
  }

  lines.push({ text: '' });
  lines.push({ text: 'Description:', bold: true, size: 10 });
  for (const w of wrapLine(String(notif.description || 'Not available.'), 84)) {
    lines.push({ text: w, size: 10 });
  }

  lines.push({ text: '' });
  lines.push({ text: 'Generated by GovTrack Recruitment Monitoring System for verification & archival.', size: 8 });

  const streamOps: string[] = ['BT'];
  let y = 760;
  for (const item of lines) {
    if (y < 50) break;
    const font = item.bold ? '/F2' : '/F1';
    const size = item.size || 10;
    streamOps.push(`1 0 0 1 50 ${y} Tm ${font} ${size} Tf (${escapePdfText(item.text)}) Tj`);
    y -= size + 5;
  }
  streamOps.push('ET');
  const contentStream = streamOps.join('\n');

  const objects: string[] = [
    '1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n',
    '2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n',
    '3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>\nendobj\n',
    `4 0 obj\n<< /Length ${Buffer.byteLength(contentStream, 'utf8')} >>\nstream\n${contentStream}\nendstream\nendobj\n`,
    '5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n',
    '6 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\nendobj\n',
  ];

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [0];
  for (const obj of objects) {
    offsets.push(Buffer.byteLength(pdf, 'utf8'));
    pdf += obj;
  }
  const xrefPos = Buffer.byteLength(pdf, 'utf8');
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i <= objects.length; i++) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefPos}\n%%EOF\n`;
  return Buffer.from(pdf, 'utf8');
}
