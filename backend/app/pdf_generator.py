import re
from typing import Dict, List


def _escape_pdf_text(text: str) -> str:
    ascii_only = re.sub(r"[^\x20-\x7E]", " ", text)
    return ascii_only.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def _wrap_line(text: str, max_len: int = 84) -> List[str]:
    words = [w for w in text.split() if w]
    lines: List[str] = []
    current = ""
    for w in words:
        candidate = f"{current} {w}".strip()
        if len(candidate) > max_len:
            if current:
                lines.append(current)
            current = w
        else:
            current = candidate
    if current:
        lines.append(current)
    return lines or [""]


def build_notification_pdf(notif: Dict[str, object]) -> bytes:
    lines: List[Dict[str, object]] = [
        {"text": "GOVTRACK - OFFICIAL RECRUITMENT NOTIFICATION SUMMARY", "bold": True, "size": 13},
        {"text": "==========================================================================", "size": 9},
        {"text": ""},
        {"text": str(notif.get("title") or "Untitled Notification"), "bold": True, "size": 12},
        {"text": ""},
    ]

    fields = [
        ("Organization", notif.get("organization_name")),
        ("Notification No.", notif.get("notification_number")),
        ("Job Category", notif.get("job_category")),
        ("Qualification", notif.get("qualification")),
        ("State / Region", notif.get("state")),
        ("Vacancy Count", notif.get("vacancy_count")),
        ("Published Date", notif.get("published_date")),
        ("Application Start", notif.get("application_start_date")),
        ("Application Deadline", notif.get("application_deadline")),
        ("Examination Date", notif.get("exam_date")),
        ("Admit Card Date", notif.get("admit_card_date")),
        ("Result Date", notif.get("result_date")),
        ("Source Mode", "DEMO DATA (Offline HTML Fixture)" if notif.get("is_demo_data") else "Live Extracted"),
        ("Original Source URL", notif.get("source_url")),
        ("Official PDF URL", notif.get("pdf_url")),
        ("First Seen At", notif.get("first_seen_at")),
        ("Last Checked At", notif.get("last_seen_at")),
    ]

    for label, val in fields:
        val_str = str(val) if val else "Not available"
        for wrapped in _wrap_line(f"{label}: {val_str}", 84):
            lines.append({"text": wrapped, "size": 10})

    lines.append({"text": ""})
    lines.append({"text": "Description:", "bold": True, "size": 10})
    for wrapped in _wrap_line(str(notif.get("description") or "Not available."), 84):
        lines.append({"text": wrapped, "size": 10})

    lines.append({"text": ""})
    lines.append({"text": "Generated by GovTrack Recruitment Monitoring System.", "size": 8})

    stream_ops = ["BT"]
    y = 760
    for item in lines:
        if y < 50:
            break
        font = "/F2" if item.get("bold") else "/F1"
        size = int(item.get("size") or 10)
        stream_ops.append(f"1 0 0 1 50 {y} Tm {font} {size} Tf ({_escape_pdf_text(str(item['text']))}) Tj")
        y -= size + 5
    stream_ops.append("ET")
    content_stream = "\n".join(stream_ops).encode("utf-8")

    objects = [
        b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n",
        b"2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n",
        b"3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>\nendobj\n",
        b"4 0 obj\n<< /Length " + str(len(content_stream)).encode("ascii") + b" >>\nstream\n" + content_stream + b"\nendstream\nendobj\n",
        b"5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n",
        b"6 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\nendobj\n",
    ]

    pdf = bytearray(b"%PDF-1.4\n")
    offsets = [0]
    for obj in objects:
        offsets.append(len(pdf))
        pdf.extend(obj)
    xref_pos = len(pdf)
    pdf.extend(f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode("ascii"))
    for offset in offsets[1:]:
        pdf.extend(f"{offset:010d} 00000 n \n".encode("ascii"))
    pdf.extend(f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref_pos}\n%%EOF\n".encode("ascii"))
    return bytes(pdf)
